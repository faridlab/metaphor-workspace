# Experiment: secret-fail-closed
#
# Fault        : the service is recreated with ONE optional module secret
#                emptied (a transient compose override generated at run
#                time from CHAOS_SECRET_ENV_VAR). This is the recreate
#                class — slow (warm re-run) and it restarts the dev
#                service. Never run it while someone else is using the stack.
# Hypothesis   : an OPTIONAL secret empty is a fail-closed surface, not a
#                boot failure: the service boots, stays healthy, keeps
#                serving every other module. (Proving the per-verb typed
#                503s needs route-shaped probes — the FULL-mode extension.)
# Blast radius : dev stack; the service container env (restored by
#                recreating WITHOUT the override); no volumes touched.
#
# Knob (required): CHAOS_SECRET_ENV_VAR — the env var name of an OPTIONAL
# secret your service consumes (e.g. a module HMAC key). Without the knob
# the experiment skips: which secret is optional is a product fact.

EXPERIMENT_NAME="secret-fail-closed"
FAULT="service recreated with ${CHAOS_SECRET_ENV_VAR:-<unset>} emptied (compose override)"
HYPOTHESIS="optional secret empty ≠ boot failure: service boots and stays healthy; other modules unaffected"
BLAST_RADIUS="dev stack, $SERVICE_NAME env only; SLOW (container recreate)"

if [ -z "${CHAOS_SECRET_ENV_VAR:-}" ]; then
    log "SKIP: $EXPERIMENT_NAME — CHAOS_SECRET_ENV_VAR not set (name of an OPTIONAL secret to empty; see docs/chaos/README.md)"
    exit 2
fi

# Generated at run time (not committed) — the var name is the parameter.
OVERRIDE_FILE="$OVERRIDES_DIR/generated-empty-secret.yaml"

write_override() {
    mkdir -p "$OVERRIDES_DIR"
    cat >"$OVERRIDE_FILE" <<EOF
# Generated by the chaos kit (secret-fail-closed) — transient, git-ignored.
services:
  $SERVICE_NAME:
    environment:
      $CHAOS_SECRET_ENV_VAR: ""
EOF
}

inject() {
    if [ "$DRY_RUN" != "1" ]; then
        write_override
    else
        printf '  [dry-run] generate override: %s emptied via %s\n' "$CHAOS_SECRET_ENV_VAR" "$(basename "$OVERRIDE_FILE")"
    fi
    run compose_ov "$OVERRIDE_FILE" up -d "$SERVICE_NAME"
    mark_injected
    check_cmd "service boots and turns ready with the secret emptied" wait_readyz "$WAIT_SLOW_TIMEOUT"
}

during_fault() {
    check_service_running "no boot-refusal crash-loop (optional secret)" "$SERVICE_NAME"
    steady_state "under-fault"
}

restore() {
    # Recreating against the BASE compose drops the override env.
    run compose_base up -d "$SERVICE_NAME"
    check_cmd "service recreated without the override" wait_readyz "$WAIT_SLOW_TIMEOUT"
    if [ "$DRY_RUN" != "1" ]; then
        rm -f "$OVERRIDE_FILE"
    fi
}
